// Launch checklist: things AI-built apps commonly ship without. These are not security
// findings: they never fail a build, and each check only runs when it applies to the app.
import { isServerEndpoint, lineAt } from './util.js';

const CODE = /\.[cm]?[jt]sx?$|\.(vue|svelte|astro)$/;
const PAGES = /\.[cm]?[jt]sx?$|\.(vue|svelte|astro|html|mdx?)$/;
const HEAD_FILES = /(^|\/)(index\.html|(src\/)?app\/layout\.[jt]sx?|pages\/_(document|app)\.[jt]sx?|app\/root\.[jt]sx?|src\/app\.html|nuxt\.config\.[jt]s|src\/layouts\/\w+\.astro|(public\/)?(manifest|site)\.(json|webmanifest))$/;

/** First match of `re` in files whose path matches `filter`, as a location. */
function locate(files, re, filter = CODE) {
  for (const f of files) {
    if (!filter.test(f.path)) continue;
    const m = re.exec(f.content);
    if (m) return { file: f.path, line: lineAt(f.content, m.index) };
  }
  return null;
}

function signals(files, ctx) {
  const dep = (re) => [...ctx.deps].some((d) => re.test(d));
  // A sign-in that only exists on an admin page doesn't mean the app has user accounts.
  const userFacing = files.filter((f) => !/(^|\/)[^/]*admin[^/]*(\/|$)/i.test(f.path));
  const inCode = (re) => !!locate(userFacing, re);
  const hostedAuthUi = dep(/^@clerk\/|^@auth0\/|^@kinde-oss\/|^@workos-inc\//);
  const accounts =
    hostedAuthUi ||
    dep(/^next-auth$|^@auth\/|^better-auth$|^lucia$/) ||
    inCode(/\.auth\.(signUp|signIn\w*)\s*\(|createUserWithEmailAndPassword|signInWithEmailAndPassword|signInWithPopup|signInWithRedirect/);
  return {
    hostedAuthUi,
    accounts,
    passwordAuth: inCode(/signInWithPassword|createUserWithEmailAndPassword|signInWithEmailAndPassword|CredentialsProvider|Credentials\(\s*\{|\.auth\.signUp\s*\(\s*\{[^}]*password/),
    payments: dep(/^stripe$|^@stripe\/|^@lemonsqueezy\/|^@paddle\/|^@polar-sh\/|^razorpay$|^@paypal\//),
    analytics: dep(/posthog|^@vercel\/analytics$|mixpanel|amplitude|^react-ga|^@next\/third-parties$|plausible|^@segment\/|umami|hotjar/i) || inCode(/googletagmanager\.com|\bgtag\s*\(/),
  };
}

const exists = (ctx, re) => ctx.paths.some((p) => re.test(p));

