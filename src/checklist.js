const boilerplateCache = new WeakMap();
function boilerplate(files) {
  if (!boilerplateCache.has(files)) {
    const hits = [];
    for (const f of files) {
      if (!HEAD_FILES.test(f.path)) continue;
      for (const b of BOILERPLATE) {
        const m = b.re.exec(f.content);
        if (m) hits.push({ file: f.path, line: lineAt(f.content, m.index), label: b.label });
      }
    }
    boilerplateCache.set(files, hits);
  }
  return boilerplateCache.get(files);
}

const aiCache = new WeakMap();
function aiServerCall(files) {
  if (!aiCache.has(files)) {
    const server = files.filter((f) => isServerEndpoint(f) || /(^|\/)(server|api|functions|lib\/server)\//.test(f.path));
    aiCache.set(files, locate(server, AI_CALL));
  }
  return aiCache.get(files);
}

/**
 * @returns {{id: string, title: string, missing: string, priority: 'must'|'should', ok: boolean, why: string, fix: string, file?: string, line?: number}[]}
 */
export function runChecklist(files, ctx, skip = new Set()) {
  if (!ctx.app) return [];
  const s = signals(files, ctx);
  const items = [];
  for (const c of CHECKS) {
    if (skip.has(c.id) || !c.applies(s, ctx, files)) continue;
    const ok = c.check(files, ctx);
    const item = { id: c.id, title: c.title, missing: c.missing, priority: c.priority(s, ctx), ok };
    if (!ok) Object.assign(item, { why: c.why(s, ctx, files), fix: c.fix(s, ctx, files) }, c.locate?.(files) ?? {});
    items.push(item);
  }
  return items.sort((a, b) => a.ok - b.ok || (a.priority === 'must' ? 0 : 1) - (b.priority === 'must' ? 0 : 1));
}
